<#
.SYNOPSIS
  Wraps data\ten.json and data\pool.json as data\ten.js and data\pool.js.

.DESCRIPTION
  Browsers block fetch() on file:// pages, so index.html loads the data with plain
  <script> tags instead. Each wrapper sets one global:
      data\ten.js   ->  window.UE_TEN  = { ...ten.json... };
      data\pool.js  ->  window.UE_POOL = { ...pool.json... };
  The JSON text is embedded byte-for-byte (after a parse check), so the wrappers can
  never drift from the source files. Re-run after data\fetch.ps1 refreshes the JSON.

.EXAMPLE
  pwsh -File build-data.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$dataDir = Join-Path $here 'data'
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Write-Wrapper {
  param(
    [Parameter(Mandatory)] [string] $JsonName,
    [Parameter(Mandatory)] [string] $JsName,
    [Parameter(Mandatory)] [string] $GlobalName
  )
  $src = Join-Path $dataDir $JsonName
  $dst = Join-Path $dataDir $JsName
  if (-not (Test-Path $src)) { throw "Missing $src" }

  $text = [System.IO.File]::ReadAllText($src, $utf8)
  # Fail loudly on malformed JSON instead of shipping a broken wrapper.
  $obj = $text | ConvertFrom-Json -Depth 64

  # JSON is a JS subset except for raw U+2028/U+2029 inside strings in older engines.
  $body = $text.Trim().Replace([string][char]0x2028, '\u2028').Replace([string][char]0x2029, '\u2029')

  $header = "/* Generated by build-data.ps1 from data/$JsonName - do not edit by hand. */"
  $out = "$header`nwindow.$GlobalName = $body;`n"
  [System.IO.File]::WriteAllText($dst, $out, $utf8)

  $count = @($obj.pitches).Count
  $kb = [math]::Round((Get-Item $dst).Length / 1KB, 1)
  Write-Host ("{0,-8} -> {1,-8} window.{2,-8} {3,4} pitches  {4,7} KB" -f $JsonName, $JsName, $GlobalName, $count, $kb)
  return $count
}

$nTen = Write-Wrapper -JsonName 'ten.json' -JsName 'ten.js' -GlobalName 'UE_TEN'
$nPool = Write-Wrapper -JsonName 'pool.json' -JsName 'pool.js' -GlobalName 'UE_POOL'

if ($nTen -ne 10) { throw "Expected 10 pitches in ten.json, found $nTen" }
if ($nPool -lt 1) { throw 'pool.json has no pitches' }
Write-Host 'OK'
